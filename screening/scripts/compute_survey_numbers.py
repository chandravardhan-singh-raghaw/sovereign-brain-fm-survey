#!/usr/bin/env python3
"""
compute_survey_numbers_v1.py
----------------------------
Reads your screening log and writes survey_numbers_v1.tex with every macro
filled, so Sections 1-2, Table 1, Table 2 and the PRISMA figure update at once.

Inputs (same folder, or pass paths as arguments):
  screened.csv      one row per record found for RQ1 (models). Columns used:
                    source_database, doi_or_arxiv, title, stage_title_abstract,
                    stage_full_text, decision, exclusion_reason
  grey.csv          one row per Indian data/compute/governance source (RQ2-3).
                    Columns used: decision  (include / exclude)
  search_log.csv    one row per database search: database, query, date, hits
                    database must be one of: PubMed, IEEE Xplore, Scopus,
                    ACM Digital Library, OpenReview, Preprints

Usage:
  python compute_survey_numbers_v1.py [screened.csv grey.csv search_log.csv]
Then set FINAL_SEARCH_DATE, AS_OF_DATE, REPO_URL, REPO_DOI below (or edit the
generated .tex) and recompile.

Duplicate rule: two records are the same if they share a DOI/arXiv id, or if
their normalised titles are identical. Keep ONE row per unique record with the
screening decision; extra rows from other databases are counted as duplicates.
"""
import csv, re, sys, collections

SCREENED = sys.argv[1] if len(sys.argv) > 1 else "screened.csv"
GREY     = sys.argv[2] if len(sys.argv) > 2 else "grey.csv"
SEARCHES = sys.argv[3] if len(sys.argv) > 3 else "search_log.csv"

FINAL_SEARCH_DATE = "30 September 2026"   # edit
AS_OF_DATE        = "October 2026"        # edit
REPO_URL          = "https://github.com/<org>/<repo>"   # edit
REPO_DOI          = "10.5281/zenodo.XXXXXXX"            # edit after Zenodo

def norm_title(t):
    return re.sub(r"[^a-z0-9]", "", t.lower())

def key(row):
    d = (row.get("doi_or_arxiv") or "").strip().lower()
    return ("id", d) if d else ("title", norm_title(row.get("title", "")))

rows = list(csv.DictReader(open(SCREENED, encoding="utf-8")))
identified = len(rows)

seen, unique = set(), []
for r in rows:
    k = key(r)
    if k in seen:
        continue
    seen.add(k); unique.append(r)
duplicates = identified - len(unique)
screened   = len(unique)

def is_inc(v): return (v or "").strip().lower() in {"include", "included", "yes", "y"}
def is_exc(v): return (v or "").strip().lower() in {"exclude", "excluded", "no", "n"}

excl_ta  = sum(1 for r in unique if is_exc(r.get("stage_title_abstract")))
fulltext = sum(1 for r in unique if is_inc(r.get("stage_title_abstract")))
excl_ft  = sum(1 for r in unique if is_inc(r.get("stage_title_abstract")) and is_exc(r.get("stage_full_text")))
included = sum(1 for r in unique if is_inc(r.get("decision")))

assert screened == excl_ta + fulltext, "every unique record needs a title/abstract decision"
assert fulltext == excl_ft + included, "every full-text record needs a final decision"

grey = list(csv.DictReader(open(GREY, encoding="utf-8")))
grey_identified = len(grey)
grey_included   = sum(1 for r in grey if is_inc(r.get("decision")))

hits = collections.Counter()
for r in csv.DictReader(open(SEARCHES, encoding="utf-8")):
    try: hits[r["database"].strip()] += int(r["hits"])
    except ValueError: pass

reasons = collections.Counter((r.get("exclusion_reason") or "").strip()
                              for r in unique if is_exc(r.get("decision")))

tex = f"""%% survey_numbers_v1.tex -- GENERATED by compute_survey_numbers_v1.py; do not edit by hand.
%% \\input this file in the PREAMBLE of main.tex. Requires url/hyperref for \\RepoURL.
\\newcommand{{\\Nmodels}}{{{included}}}
\\newcommand{{\\Nidentified}}{{{identified}}}
\\newcommand{{\\Nduplicates}}{{{duplicates}}}
\\newcommand{{\\Nscreened}}{{{screened}}}
\\newcommand{{\\Nexcludedta}}{{{excl_ta}}}
\\newcommand{{\\Nfulltext}}{{{fulltext}}}
\\newcommand{{\\Nexcludedft}}{{{excl_ft}}}
\\newcommand{{\\Ngrey}}{{{grey_included}}}
\\newcommand{{\\Ngreyidentified}}{{{grey_identified}}}
\\newcommand{{\\FinalSearchDate}}{{{FINAL_SEARCH_DATE}}}
\\newcommand{{\\AsOfDate}}{{{AS_OF_DATE}}}
\\newcommand{{\\RepoURL}}{{\\url{{{REPO_URL}}}}}
\\newcommand{{\\RepoDOI}}{{{REPO_DOI}}}
\\newcommand{{\\HitsPubMed}}{{{hits.get('PubMed', 0)}}}
\\newcommand{{\\HitsIEEE}}{{{hits.get('IEEE Xplore', 0)}}}
\\newcommand{{\\HitsScopus}}{{{hits.get('Scopus', 0)}}}
\\newcommand{{\\HitsACM}}{{{hits.get('ACM Digital Library', 0)}}}
\\newcommand{{\\HitsOpenReview}}{{{hits.get('OpenReview', 0)}}}
\\newcommand{{\\HitsArxiv}}{{{hits.get('Preprints', 0)}}}
"""
open("survey_numbers_v1.tex", "w", encoding="utf-8").write(tex)

print(f"identified {identified} | duplicates {duplicates} | screened {screened} | "
      f"excluded T/A {excl_ta} | full text {fulltext} | excluded FT {excl_ft} | included {included}")
print(f"grey: identified {grey_identified}, included {grey_included}")
print("hits:", dict(hits))
print("exclusion reasons:", dict(reasons))
print("wrote survey_numbers_v1.tex")
